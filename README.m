# 🛍️ Mall Customer Segmentation using K-Means Clustering

A K-Means clustering model to group retail store customers based on their purchase history using the Mall Customer Dataset.

## 📌 Task
SkillCraft Technology - Task 02

## 📊 Dataset
[Mall Customer Dataset](https://www.kaggle.com/datasets/vjchoudhary7/customer-segmentation-tutorial-in-python)

## 🔧 Features Used
- Age
- Annual Income (k$)
- Spending Score (1-100)

